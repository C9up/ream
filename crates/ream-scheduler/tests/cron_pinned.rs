fn fires(expr: &str, after: &str, count: usize) -> Vec<String> {
    let schedule = parse_cron(expr).unwrap_or_else(|e| panic!("{expr:?} must parse: {e}"));
    let mut at: Timestamp = after
        .parse()
        .unwrap_or_else(|e| panic!("bad fixture instant {after:?}: {e}"));
    let mut out = Vec::new();
    while out.len() < count {
        let Some(next) = schedule.next_after(at) else {
            break;
        };
        out.push(next.strftime("%Y-%m-%dT%H:%M:%SZ %a").to_string());
        at = next;
    }
    out
}

#[test]
fn next_fires_match_the_pinned_table() {
    let mut mismatches = Vec::new();
    for (expr, after, expected) in CASES {
        let got = fires(expr, after, 3);
        if got != *expected {
            mismatches.push(format!(
                "{expr:?} after {after}:\n  expected {expected:?}\n  got      {got:?}"
            ));
        }
    }
    assert!(mismatches.is_empty(), "{}", mismatches.join("\n"));
}

#[test]
fn rejected_expressions_stay_rejected() {
    let accepted: Vec<&str> = REJECTED
        .iter()
        .copied()
        .filter(|expr| parse_cron(expr).is_ok())
        .collect();
    assert!(accepted.is_empty(), "accepted: {accepted:?}");
    for expr in REJECTED {
        let err = parse_cron(expr).err().map(|e| e.code);
        assert_eq!(err.as_deref(), Some("INVALID_CRON"), "{expr:?}");
    }
}
