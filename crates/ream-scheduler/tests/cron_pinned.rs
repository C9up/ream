//! contract: an implementation change that moves any fire time, or accepts an
//! expression listed as rejected, fails here.
//!
//! Each row is `(expression, after, next three fires)`: the first fire is the
//! first one strictly after `after`, each following one the first strictly
//! after the previous. A short list means the schedule stops there; an empty
//! one means it never fires again. Fires are written in UTC with the weekday,
//! so a day-of-week mistake reads as one.

