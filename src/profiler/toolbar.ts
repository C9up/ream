/**
 * The bar at the bottom of the page.
 *
 * It carries its own token inline rather than reading `X-Debug-Token` off the
 * response: a script in a page cannot see the headers of the navigation that
 * delivered it. Symfony injects the token for the same reason.
 *
 * Everything lives in a shadow root — your stylesheet must not reach the bar,
 * and the bar must not reach your page. It fetches its numbers once, on load,
 * and then does nothing: a dev tool that polls is a dev tool that shows up in
 * its own history.
 *
 * A string rather than a stringified function, as the hot-reload script is:
 * this package compiles without the DOM library, deliberately — it is a server
 * — so browser code here is text, and its only inputs are escaped below.
 *
 * It styles its nodes through the CSSOM — `node.style.cssText` — rather than
 * with a `<style>` element. Under a CSP with `style-src 'self'` (or only a
 * `default-src`, which is the common case) a stylesheet inserted at runtime is
 * inline style and is dropped, with no error anywhere: the bar renders as a
 * stack of grey text and nothing says why. Setting properties on an element is
 * not inline style and is never blocked, which is also how the host below has
 * always been positioned.
 */

import { PROFILER_PATH } from './Profiler.js'

/**
 * The `<script>` to append to an HTML response.
 *
 * `token` is generated by the profiler (hex) and `nonce` by the response, so
 * neither is user input; both are still put through `JSON.stringify` rather
 * than interpolated raw, because "cannot contain a quote" is an invariant that
 * holds until someone changes how one of them is made.
 */
export function toolbarScript(token: string, nonce?: string): string {
  const attribute = nonce === undefined ? '' : ` nonce="${nonce.replace(/"/g, '&quot;')}"`
  const config = JSON.stringify({ token, path: PROFILER_PATH })
  return `<script${attribute}>(${BAR})(${config})</script>`
}

/**
 * The bar, as it runs in the browser.
 *
 * Kept on one indented block so what ships is readable in a page's source —
 * someone will open the inspector and find this, and a minified blob would
 * tell them nothing about where it came from.
 */
const BAR = `function(c){
  var host=document.createElement('div');
  host.style.cssText='position:fixed;left:0;right:0;bottom:0;z-index:2147483000';
  var root=host.attachShadow({mode:'closed'});
  document.body.appendChild(host);
  var bar=document.createElement('div');
  bar.style.cssText='display:flex;align-items:stretch;background:#14161a;color:#e6e6e6;'
    +'font:12px/1 ui-monospace,Menlo,monospace;border-top:1px solid #262a31;'
    +'box-shadow:0 -2px 8px rgba(0,0,0,.4)';
  root.appendChild(bar);
  var page=c.path+'/'+c.token;
  var COLOR={bad:'#ff7b72',warn:'#f0883e',ok:'#7ee787'};
  function cell(label,value,tone,plain){
    var node=document.createElement('div');
    node.style.cssText='padding:7px 11px;white-space:nowrap;'
      +(plain?'flex:1;overflow:hidden;text-overflow:ellipsis;cursor:default'
             :'border-right:1px solid #21252c;cursor:pointer');
    if(label){
      var tag=document.createElement('span');
      tag.style.cssText='color:#8b949e;margin-right:6px';
      tag.textContent=label;
      node.appendChild(tag);
    }
    var text=document.createElement('span');
    if(tone){text.style.color=COLOR[tone];}
    text.textContent=value;
    node.appendChild(text);
    if(!plain){
      node.addEventListener('mouseenter',function(){node.style.background='#1b1f25'});
      node.addEventListener('mouseleave',function(){node.style.background=''});
      node.addEventListener('click',function(){window.open(page,'_blank')});
    }
    bar.appendChild(node);
  }
  function panel(data,name){
    var value=data&&data[name];
    return (value&&typeof value==='object')?value:null;
  }
  fetch(page+'.json',{headers:{accept:'application/json'}})
    .then(function(r){return r.ok?r.json():null})
    .then(function(p){
      if(!p){host.remove();return}
      var status=Number(p.status||0);
      cell('',String(status),status>=500?'bad':status>=400?'warn':'ok');
      cell('time',Number(p.duration||0).toFixed(1)+' ms');
      var db=panel(p.data,'database');
      if(db){
        var total=Number(db.total||0);
        cell('db',total+' \u00b7 '+Number(db.duration||0).toFixed(1)+' ms',total>=50?'warn':'');
      }
      var mem=panel(p.data,'memory');
      if(mem){cell('mem',Number(mem.usedMb||0).toFixed(1)+' MB');}
      var err=panel(p.data,'exception');
      if(err&&typeof err.message==='string'){cell('',err.message,'bad');}
      cell('',String(p.url||''),'',true);
    })
    .catch(function(){host.remove()});
}`
