/**
 * The tag that loads the debug toolbar into an HTML page.
 *
 * A `<script src>` with the request's profile token in a data attribute, and
 * nothing inline. The bar itself — `client/toolbar.js` and `client/toolbar.css`
 * — is served by the profiler endpoint from the same origin, so a policy of
 * `script-src 'self'` / `style-src 'self'` runs and styles it, and a
 * nonce-only policy runs it through the nonce stamped here. An inline script,
 * which is what this used to be, needed the nonce and nothing else would do.
 *
 * The token travels in the page rather than being read off the response: a
 * script cannot see the headers of the navigation that delivered it. Symfony
 * injects its token for the same reason.
 */

import { PROFILER_PATH } from './Profiler.js'

/** Where the toolbar's own files are served, under the profiler's path. */
export const PROFILER_ASSETS_PATH = `${PROFILER_PATH}/_assets`

/**
 * The `<script>` to append to an HTML response.
 *
 * `token` is generated by the profiler (hex) and `nonce` by the response, so
 * neither is user input; both are still attribute-escaped, because "cannot
 * contain a quote" is an invariant that holds until someone changes how one of
 * them is made.
 */
export function toolbarScript(token: string, nonce?: string): string {
  const attribute = nonce === undefined ? '' : ` nonce="${escapeAttribute(nonce)}"`
  return (
    `<script src="${PROFILER_ASSETS_PATH}/toolbar.js" data-token="${escapeAttribute(token)}"` +
    ` data-path="${PROFILER_PATH}"${attribute}></script>`
  )
}

function escapeAttribute(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
}
