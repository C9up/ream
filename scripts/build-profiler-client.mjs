#!/usr/bin/env node
/**
 * Write src/profiler/client.generated.ts from the toolbar's browser files.
 *
 * The toolbar is authored as a real .js and .css file, so it is linted and
 * readable, but the package compiles without the DOM library and must not read
 * files next to its build output at runtime. The two files are embedded as
 * strings instead; `tests/unit/profiler-client.test.ts` fails when this was
 * not re-run after an edit.
 *
 *     node scripts/build-profiler-client.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const client = join(root, 'src', 'profiler', 'client')

export function generate() {
  const js = readFileSync(join(client, 'toolbar.js'), 'utf8')
  const css = readFileSync(join(client, 'toolbar.css'), 'utf8')
  return `// Generated by scripts/build-profiler-client.mjs from src/profiler/client/. Do not edit.

/** The debug toolbar's script, served at /__ream/profiler/_assets/toolbar.js. */
export const TOOLBAR_JS: string = ${JSON.stringify(js)}

/** The debug toolbar's stylesheet, served at /__ream/profiler/_assets/toolbar.css. */
export const TOOLBAR_CSS: string = ${JSON.stringify(css)}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'src', 'profiler', 'client.generated.ts'), generate())
}
